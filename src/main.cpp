// ── Time sync (browser-pushed Unix timestamp) ──────────────────────
static volatile uint32_t timeUnixBase   = 0;   // Unix time at sync point
static volatile uint32_t timeMillisBase = 0;   // millis() at sync point
static volatile bool     timeSynced     = false;

// Seconds since boot. gBootMillis is set once in setup(); using a dedicated
// counter keeps the FSD-mock-only build free of the legacy `cfg` state.
static inline uint32_t bootUptimeSeconds() {
    return (millis() - gBootMillis) / 1000;
}

// Returns Unix timestamp (when synced) or seconds-since-boot (fallback).
static inline uint32_t getUnixTime() {
    if (timeSynced) return timeUnixBase + (millis() - timeMillisBase) / 1000;
    return bootUptimeSeconds();
}

// ── Auth ──────────────────────────────────────────────────────────
static char sessionToken[17] = {0};  // 16 hex chars, reset on reboot
static char storedPin[17]    = {0};  // loaded from NVS; empty = no auth

static void generateToken() {
    uint32_t r1 = esp_random(), r2 = esp_random();
    snprintf(sessionToken, sizeof(sessionToken), "%08X%08X",
             static_cast<unsigned>(r1), static_cast<unsigned>(r2));
}

// Returns true if request is authorised.
// If no PIN is configured, always returns true (open access).
static bool checkToken(AsyncWebServerRequest* req) {
    if (storedPin[0] == '\0') return true;           // no PIN set → open
    if (sessionToken[0] == '\0') return false;        // PIN set but no token yet
    if (req->hasParam("token") &&
        req->getParam("token")->value().equals(sessionToken)) return true;
    return false;
}

// Refuse memory-heavy pages/streams when the heap is already thin. A live
// vehicle TLS session can hold ~25-30 KB; serving an 8-10 KB management page
// concurrently previously pushed free heap below 2 KB under synthetic load.
// Lightweight health endpoints (/api/wifi-bridge/status, /api/fsd-mock/payload)
// stay available so monitoring and FSD delivery keep working.
static bool rejectOnLowHeap(AsyncWebServerRequest* req, uint32_t minFree = 18000) {
    if (ESP.getFreeHeap() >= minFree) return false;
    req->send(503, "text/plain", "low_heap");
    return true;
}

