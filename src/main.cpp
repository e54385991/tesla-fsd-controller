// One-time migration of AP/PIN keys from very old verbose names and cleanup of
// retired CAN-injection / legacy single-STA keys so the NVS partition stays lean.
static void migrateNvsKeys() {
    Preferences p;
    if (p.begin("fsd", false)) {
        if (!p.isKey(NV_AP_SSID) && p.isKey("apSSID")) {
            p.putString(NV_AP_SSID, p.getString("apSSID"));
            p.remove("apSSID");
        }
        if (!p.isKey(NV_AP_PASS) && p.isKey("apPass")) {
            p.putString(NV_AP_PASS, p.getString("apPass"));
            p.remove("apPass");
        }
        const char* retired[] = {
            "a1", "a2", "a3", "a4", "a5", "a6", "a7", "a8", "a9",
            "b1", "b2", "b3", "b4", "b5", "b6", "b7", "b8", "b9",
            "c1", "c2", "c3", "c6", "c7",
            "d1", "d2", "d3", "d4", "d5", "d6", "d7", "d8", "d9",
            "da", "db", "dc", "dd", "de", "df", "dg", "dh",
            "e0", "e1", "e2",
            "fsdEn", "hwMode", "spPro", "proAuto", "isaChm", "emDet",
            "cnMode", "apRestart", "precond", "staSSID", "staPass",
            "ping_en",
        };
        for (auto* k : retired) {
            if (p.isKey(k)) p.remove(k);
        }
        p.end();
    }
    Preferences sec;
    if (sec.begin("sec", false)) {
        if (!sec.isKey(NV_PIN) && sec.isKey("pin")) {
            sec.putString(NV_PIN, sec.getString("pin"));
            sec.remove("pin");
        }
        sec.end();
    }
}

