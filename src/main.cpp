    // WiFi AP settings — save to NVS then restart
    server.on("/api/wifi", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (!checkToken(req)) { req->send(403, "text/plain", "UNAUTH"); return; }
        if (!req->hasParam("ssid", true)) {
            req->send(400, "text/plain", "Missing ssid");
            return;
        }
        String newSSID = req->getParam("ssid", true)->value();
        String newPass = req->hasParam("pass", true) ? req->getParam("pass", true)->value() : "";
        newSSID.trim();
        if (newSSID.length() == 0 || newSSID.length() > 32) {
            req->send(400, "text/plain", "SSID must be 1-32 chars");
            return;
        }
        if (newPass.length() > 0 && newPass.length() < 8) {
            req->send(400, "text/plain", "Password must be >= 8 chars");
            return;
        }
        Preferences wPrefs;
        wPrefs.begin("fsd", false);
        wPrefs.putString(NV_AP_SSID, newSSID);
        if (newPass.length() >= 8) wPrefs.putString(NV_AP_PASS, newPass);
        wPrefs.end();
        req->send(200, "text/plain", "OK");
        saveRestartReason("/api/ap save");
        otaPendingRestart = true;
    });

    // WiFi scan — two-endpoint non-blocking design:
    //   GET /api/scan        → kick off async scan, return immediately
    //   GET /api/scan/result → poll for completion; returns {"scanning":true} while
    //                          in progress, or the deduplicated RSSI-sorted SSID array.
    server.on(AsyncURIMatcher::exact("/api/scan"), HTTP_GET, [](AsyncWebServerRequest* req) {
        if (!checkToken(req)) { req->send(403, "text/plain", "UNAUTH"); return; }
        if (WiFi.scanComplete() == WIFI_SCAN_RUNNING) {
            req->send(200, "application/json", "{\"scanning\":true,\"already\":true}");
            return;
        }
        WiFi.scanDelete();
#if ESP_ARDUINO_VERSION_MAJOR >= 3
        // Shorter active dwell (40..120 ms/ch) cuts total off-channel sweep
        // time by ~60%, preventing AP clients from dropping during scans.
        WiFi.setScanActiveMinTime(40);
#endif
        WiFi.scanNetworks(/*async=*/true, /*hidden=*/false,
                          /*passive=*/false, /*max_ms_per_chan=*/120,
                          /*channel=*/0);
        req->send(200, "application/json", "{\"scanning\":true}");
    });

    server.on("/api/scan/result", HTTP_GET, [](AsyncWebServerRequest* req) {
        if (!checkToken(req)) { req->send(403, "text/plain", "UNAUTH"); return; }
        int n = WiFi.scanComplete();
        if (n == WIFI_SCAN_RUNNING) {
            req->send(200, "application/json", "{\"scanning\":true}");
            return;
        }
        uint32_t up = bootUptimeSeconds();
        if (n <= 0) {
            char logMsg[48];
            snprintf(logMsg, sizeof(logMsg), "WiFi scan: %d networks (err=%d)", n, n);
            addDiagLog(up, logMsg);
            WiFi.scanDelete();
            req->send(200, "application/json", "[]");
            return;
        }
        char logMsg[48];
        snprintf(logMsg, sizeof(logMsg), "WiFi scan: %d networks found", n);
        addDiagLog(up, logMsg);

        // Deduplicate by SSID (keeping strongest RSSI), skip empty SSIDs, and
        // sort descending by RSSI so the strongest hotspots appear first.
        struct ScanItem {
            char ssid[33];
            int32_t rssi;
        };
        constexpr size_t kMaxScanItems = 32;
        ScanItem items[kMaxScanItems];
        size_t itemCount = 0;
        for (int i = 0; i < n; i++) {
            String ssid = WiFi.SSID(i);
            if (ssid.isEmpty()) continue;
            const int32_t rssi = WiFi.RSSI(i);
            bool dup = false;
            for (size_t j = 0; j < itemCount; ++j) {
                if (ssid.equals(items[j].ssid)) {
                    if (rssi > items[j].rssi) items[j].rssi = rssi;
                    dup = true;
                    break;
                }
            }
            if (!dup && itemCount < kMaxScanItems) {
                strlcpy(items[itemCount].ssid, ssid.c_str(), sizeof(items[itemCount].ssid));
                items[itemCount].rssi = rssi;
                ++itemCount;
            }
        }
        WiFi.scanDelete();

        for (size_t i = 0; i + 1 < itemCount; ++i) {
            size_t best = i;
            for (size_t j = i + 1; j < itemCount; ++j) {
                if (items[j].rssi > items[best].rssi) best = j;
            }
            if (best != i) {
                ScanItem tmp = items[i];
                items[i] = items[best];
                items[best] = tmp;
            }
        }

        String json = "[";
        json.reserve(itemCount * 48 + 4);
        for (size_t i = 0; i < itemCount; ++i) {
            if (i > 0) json += ",";
            char escaped[72];
            jsonEscapeInto(items[i].ssid, escaped, sizeof(escaped));
            json += "{\"ssid\":\"";
            json += escaped;
            json += "\",\"rssi\":";
            json += String(items[i].rssi);
            json += "}";
        }
        json += "]";
        req->send(200, "application/json", json);
    });

    // Time sync — browser pushes its Unix timestamp
    server.on("/api/time", HTTP_POST, [](AsyncWebServerRequest* req) {
        if (!checkToken(req)) { req->send(403, "text/plain", "UNAUTH"); return; }
        if (!req->hasParam("ts", true)) { req->send(400, "text/plain", "Missing ts"); return; }
        uint32_t ts = (uint32_t)req->getParam("ts", true)->value().toInt();
        if (ts < 1700000000UL) { req->send(400, "text/plain", "Invalid"); return; }
        timeUnixBase   = ts;
        timeMillisBase = millis();
        timeSynced     = true;
        struct timeval tv = {};
        tv.tv_sec = ts;
        settimeofday(&tv, nullptr);
        req->send(200, "text/plain", "OK");
    });

